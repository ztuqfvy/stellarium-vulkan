/*
 * LifeCycleCheck — T44-C：**生命周期回归自检**（STELQUICK_LIFECYCLE_CHECK=1）。
 *
 * ── 这笔账挂得有多早 ───────────────────────────────────────────────────────
 * 测试文档 §6.4 的窗口自测里写着 `window->hide();  // 关闭代理：隐藏窗口
 * （真·关闭重开见 P-LIF ×100 回归）` —— 也就是说，从 A1 起「关闭/重开 ×100」
 * 一直是被 `hide()` **代理掉**的欠账：`hide()` 只有"窗口不可见"这一个语义，
 * 验不到场景图资源重建、帧队列有界、恢复后帧号推进。A-1.0 出口第 3 条要求它还上。
 *
 * ── 为什么要 ×100，以及为什么用替身生产者 ───────────────────────────────────
 * 引擎形态单次启动的真实预热是 ~900s（T9 实测）⇒ 100 × 900s ≈ 25 小时，物理不可行。
 * 本组验的是**帧通路与窗口/场景图资源的寿命**，与"帧从哪来"无关 ⇒ 用替身生产者
 * `LiveFrameSource`（独立线程 + kOwn 离屏上下文）。**产品代码路径零改动**：
 * `FrameMailbox` / `SkyViewport` / 上传 / 上屏全是真的，被替换的只有"帧的产出者"。
 *
 * ⚠️ **诚实性声明（必须与结论一起读）**：本组判据**不覆盖**引擎 GL 资源在窗口
 * 生命周期上的释放。结论严格限定为：
 *   「在给定帧率与尺寸下，窗口/场景图/邮箱在 100 轮生命周期事件下不崩、不死锁、
 *     不无界增长、恢复后帧号重新推进」 —— 不含"引擎纹理无泄漏"。
 *
 * ── 判据逐条（编号连续；台账 id 必须逐字一致 —— 陷阱 85）────────────────────
 *  LF-02a 最小化/恢复 ×100：帧队列**有界且不积压**。
 *         ⚠️ 单判 `completeSlots ≤ kFrameSlotCount` 是**平凡真**：那是定长数组的构造
 *         性质，`> 3` 不可能发生（陷阱 67）。真正的有界性来自 U-FRM-01「忙时丢帧、
 *         不积压」⇒ 必须同时判"最新完整帧的年龄不无界增长"（peak ≤ kAgeBudgetMs）。
 *  LF-02b 最小化/恢复 ×100：帧号**每轮推进**，判"**最长连续零推进 ≤ 1**"。
 *         ⚠️ 不判"零推进轮数 == 0"是留给单次事件循环打嗝一格余量；**收敛期必须给足**
 *         （见下），否则 0 会成片出现 —— 那就是仪器问题，不是被测物问题。
 *  LF-02c 最小化/恢复 ×100：视口全程 `ready == true`（最小化期间视口对象不就绪 = 资源被拆）。
 *  LF-02d 最小化/恢复 ×100：每轮恢复后几何**回归基线**（"画面恢复正确"的几何面）。
 *  LF-02e 最小化/恢复 ×100：`phys_footprint` 首末增量**有界**（记录性判据，阈值实测写死）。
 *  LF-02f 最小化/恢复 ×100：**窗口态真的进过「最小化」**（最小化稳态 `windowStates()`
 *         含 `WindowMinimized`，恢复后回 `WindowNoState`）。
 *         这条是 A1 那笔欠账的正面判据：`hide()` 代理**进不了这个状态** ⇒ 负控 HIDE
 *         恰好钉死在这里（否则 HIDE 会全绿 = 无效负控，陷阱 20）。
 *  LF-03a 尺寸切换 ×100：世代**递增**次数 ≥ 有效尺寸变化次数 − 1（留 1% 容差，
 *         给单次事件循环打嗝；实测正题 100/100）。
 *         ⚠️ 早期注释写的"首次可能与 Qt 初始 resize 合并"是**归因假象** —— 探针首测
 *         Δ=[0,1,1,1] 的真因是它轮询 0ms 就成功、本轮的 `geometryChange` 还没处理，
 *         bump 串进了下一个测量窗（探针加"动作前重照 prev"护栏后复测 Δ=[1,1,1,1]，
 *         首帧延迟 30ms）。判据侧不受影响：350ms 收敛期覆盖了 bump。
 *  LF-03b 尺寸切换 ×100：世代**单调不减**（任何一次回退都说明世代语义坏了）。
 *  LF-03c 尺寸切换 ×100：切换后帧号仍推进（最长连续零推进 ≤ 1，同 LF-02b 口径）。
 *  LF-03d 尺寸切换 ×100：`phys_footprint` 首末增量有界（同 LF-02e 口径）。
 *  LF-04a 组合序列 ×100（最小化/恢复 与 尺寸切换 交替）：世代仍递增。
 *  LF-04b 组合序列 ×100：帧队列仍有界（同 LF-02a 口径：槽位数 + 帧龄）。
 *  LF-04c 组合序列 ×100：帧号仍推进（最长连续零推进 ≤ 1）。
 *
 * ── ⚠️ 收敛期（本组最关键的一条仪器纪律，别省）─────────────────────────────
 * 本组第一版把步进结构的时序写反了（`delayAfter` 语义 = "跑完本步之后等"，陷阱 41），
 * 结果 `Step{0, doResize}` → `Step{260, 采样}` 里的采样**在 setGeometry 之后 0ms 就执行**，
 * 那 260ms 等在了采样之后 ⇒ 全程读到 `世代 X→X` / `帧号 +0` / `投递 +0`，
 * 看上去像"尺寸切换把帧通路打死了"的**重大产品缺陷**，实际是仪器把"0ms 后的世界"
 * 当成了"260ms 后的世界"（新陷阱 102）。
 * 现语义为 `Step::waitBefore`（**跑本步之前等**），并且三个收敛期**实测写死**：
 *   · 最小化 500ms / 恢复 400ms / 尺寸 350ms。
 *   不给收敛期直接采样 = 读数全部退化为 0（`STELQUICK_LIFECYCLE_NOSETTLE` 就是这个，
 *   它作为**仪器灵敏度回归哨兵**，必须会红）。
 *
 * ── 与 `Q-WIN-01…06` 不许互相搭便车（陷阱 22）─────────────────────────────
 * `Q-WIN-01/02/04` 也拿 `setGeometry` 打窗口，但判的是**主线程停顿/帧间隔**
 * （`maxStallMs ≤ 250ms`）。本组判的是**世代递增 + 内存不无界增长**。
 * 各判各的命题，共用布场 ≠ 共用证据。
 *
 * ── 纪律（T40/T41/T42 血泪）─────────────────────────────────────────────
 *  · 台账 id 用**显式列表** + `finish()` 做"未被记账的 id"自证（陷阱 85：
 *    症状是"判据 N/N 却 VERDICT=FAIL"）。
 *  · 收割回调必须是 `Ctx` 的成员（陷阱 84：漏赋值 ⇒ 零判据输出）。
 *  · 判据只许验**被声称的命题**（陷阱 75）：额外加戏 = 自造红项。
 *  · 收尾必须把窗口还原到**布场态**（陷阱 90：无条件恢复会自己修好被负控打断的路径）。
 *  · 负控期望值**必须实跑出来再写死**（陷阱 87）。
 *  · 诊断里每个量都要标清窗口口径（"本轮" vs "25 轮"）；诊断基准在**每组开头
 *    rebase**，否则首个窗口打印的是"开机以来累计值"与后续窗口增量不同量纲
 *    （首版实测 `leased +1298` / `hostReq +5519` 就是这个，陷阱 65/56 同族）。
 *  · 前提不齐（无窗口 / 无视口 / 替身生产者未装配 / 基线期帧就不流）⇒
 *    **UNAVAILABLE**，不记 FAIL（陷阱 3：仪器没接在实况上，那是仪器问题不是被测物问题）。
 */
#pragma once

#include <QString>
#include <QStringList>
#include <functional>

class QCoreApplication;
class QQuickWindow;

namespace stelapp {

class FrameMailbox;
class IFrameProducer;

class LifeCycleCheck
{
public:
    struct Result
    {
        bool ran = false;
        bool unavailable = false;
        bool pass = false;
        int passed = 0;
        int total = 0;
        QString summary;
        QStringList details;
    };

    //! 全部在 GUI 线程。@p delayMs 后开跑（等 QML/场景图落定）。
    //! @p producer 是**前提**：帧流不在，本组所有"推进"类判据都无意义 ⇒ 报 UNAVAILABLE。
    static void run(QCoreApplication *app,
                    QQuickWindow *window,
                    FrameMailbox *mailbox,
                    IFrameProducer *producer,
                    const std::function<void(const Result &)> &onDone,
                    int delayMs = 1500);
};

} // namespace stelapp
