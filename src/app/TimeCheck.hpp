/*
 * TimeCheck — T19「改时间」环自检（STELQUICK_TIME_CHECK=1）。
 *
 * 与 A2FrameCheck / DynFrameCheck / AppFacadeCheck / SearchModelCheck / LocateCheck 同风格：
 * 装配在 main.cpp 完成（引擎已 boot、帧泵已 start、AppFacade 已建），
 * 本类只消费就绪对象，跑完经回调回传。
 *
 * ── 判据设计的核心：**往返** + **成对** ────────────────────────────────────────
 * 时间环最容易出的两类错，恰好都能被同一招抓住：
 *
 *   ① 时区方向搞反（写 `-offset`、读也 `-offset`，或两个都 `+`）。
 *      症状是"输入 14:30 回显 22:30"，而**任何只看单边的判据都是绿的**：
 *      JD 写进去了（对）、JD 读出来有值（对）。只有**往返**才抓得到。
 *      ⇒ TC-01..03 写 (y,m,d,h,min,s) → 读回同 6 字段，逐字段必须相等。
 *      ⇒ TC-06 反向也来一遍：读本地字段 → 原样写回 → JD 必须复原。
 *
 *   ② 日历/儒略日算法被"重新发明"。副作用是把 1582 年儒略/格里历切换、
 *      闰年规则、闰秒口径全都复制一遍，然后与引擎在边界上各自漂移。
 *      ⇒ TC-05 把写入结果与**旧 DateTimeDialog::newJd() 的公式**逐位比对
 *        （容差 1e-9 天 ≈ 0.09 ms）——这是"没有另立一套"的机械证据。
 *      ⇒ TC-02/TC-03 特意取**跨年边界**与**闰日**，正是自造算法会翻车的点。
 *
 *   ③ 写入被帧泵拽回（T15 的宿主闭式公式就会这样；T16 才修掉）。
 *      ⇒ TC-13 在**运行态**（未暂停）跳 0.5 天，等一拍，断言 JD 停在
 *        "跳转目标 + 实测墙钟 × 速率"上，而不是弹回跳转前的值。
 *
 * 成对（判别性对照）是防假绿的第二层：
 *   · TC-04 三组输入的读回值必须**彼此不同** —— 否则"读回"可能是个常量；
 *   · TC-10 写回**同一个** JD → 星空必须**不动**（< 0.05°）—— 否则 TC-09 的
 *     "星空动了"可能只是"测量噪声很大"；
 *   · TC-11 跳回原时刻 → 星空必须**复原** —— 否则"动"可能不可逆（写坏了）。
 *
 * ── 为什么要**暂停**时钟 ──────────────────────────────────────────────────────
 * 自检环境的 `simRate = 0.1 天/秒`（1 秒墙钟 = 2.4 小时天空）。跨步骤的等待
 * （300 ms）就会带来 0.03 天（43 分钟）的自然漂移 —— 那会把"往返恒等"这类
 * 子毫秒级的判据整个淹掉。所以**先暂停时钟**（`setSimulationPaused(true)`，
 * 即 simClock.scale=0：帧泵照跑、JD 冻结），把纯时间判据放在冻结区里做；
 * 只有 TC-13 需要运行态，它在最后单独恢复再测。
 *
 * ── 判据清单 ─────────────────────────────────────────────────────────────────
 *   TC-01 往返恒等·常规日期      2026-09-24 14:30:00 → 读回逐字段相等
 *   TC-02 往返恒等·跨年边界      2026-12-31 23:59:59 → 读回逐字段相等
 *   TC-03 往返恒等·闰日          2024-02-29 12:00:00 → 读回逐字段相等
 *   TC-04 读回**确实依赖输入**（判别性对照）：上三组读回互不相同
 *   TC-05 与旧对话框公式逐位一致（容差 1e-9 天）——"不重新发明算法"的机械证据
 *   TC-06 UTC 往返（非零偏移下）：读本地字段 → 原样写回 → JD 复原
 *   TC-07 utcOffsetHours 与 core->getUTCOffset(jd) 一致（API 契约；并打印偏移本身）
 *   TC-08 非法输入被拒**且无副作用**（13 月 / 32 日 / 25 时 三组）
 *   TC-09 世界确实动了（I-DYN-02）：跳 +0.25 天 → 目标 AltAz 变化 > 5°
 *   TC-10 判别性对照：写回同一 JD → AltAz 变化 < 0.05°
 *   TC-11 可逆：跳回原时刻 → AltAz 复原 < 0.05°
 *   TC-12 "现在"：先跳 1900-01-01（差值必 > 100 天），setTimeNow 后 < 1e-3 天
 *   TC-13 写入不被帧泵拽回：运行态跳 0.5 天，JD 停在"目标 + 实测漂移"上
 *   TC-14 超范围 JD 被拒（out-of-range）且无副作用
 *
 * TC-09/10/11 需要选中一个天体；**取不到 fixture 时照实 SKIP**（note 不计入
 * 判据数），不让环境条件把整份报告污染成 FAIL —— 但其余 11 条与环境无关。
 *
 * ── 退出码 ───────────────────────────────────────────────────────────────────
 *   0=PASS，10=FAIL，6=UNAVAILABLE（引擎未引导 —— 环境条件，照实报）。
 */
#pragma once

#include <QString>
#include <QStringList>
#include <functional>

class QCoreApplication;

namespace stelapp {

class AppFacade;

class TimeCheck
{
public:
    struct Result
    {
        bool ran = false;          //!< 真正跑过（前置满足）
        bool pass = false;
        bool unavailable = false;  //!< 引擎未引导（环境条件，非逻辑缺陷）
        int passed = 0;
        int total = 0;
        QString summary;
        QStringList details;
    };

    //! 全部在 GUI 线程。@p delayMs 后开跑（等引擎数据落定）。结果经 onDone 回传。
    static void run(QCoreApplication *app,
                    AppFacade *facade,
                    const std::function<void(const Result &)> &onDone,
                    int delayMs = 2000);
};

} // namespace stelapp
