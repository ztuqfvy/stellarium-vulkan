/*
 * LocationCheck — T33-C 观察地点写入面自检（STELQUICK_LOC_CHECK=1）。
 *
 * ── 为什么要分两条腿（TRAPS 第 8 条）─────────────────────────────────────────
 * "规则正确"与"规则被调用"是两件事。范围闸在 `AppFacade::isAcceptableLatitude`
 * 之类的**纯谓词**里（LC-01 恒可跑，不需要引擎）；而"这次写入真的到了引擎、
 * 世界真的跟着变了"只能由**活引擎腿**证（LC-03..LC-07）。
 * 缺任何一条都有假绿空间：只写纯逻辑 → 注掉写入路径判据全绿（T21 的血泪）；
 * 只写活引擎 → 范围闸的边界（±90 恰好放行、91 恰好拒）测不全。
 *
 * ── 判据设计：成对 + 判别对照 + 可验算的物理量 ───────────────────────────────
 *   LC-02 读面：当前地点非空、经纬度在范围内。
 *   LC-03a **写入生效（成对）**：写跨时区地点（Paris）⇒
 *         (a) 回读的 lat/lon/name 变成目标值（世界确实动了）∧
 *         (b) 引擎的 UTCOffset 跟着变（**独立于地点 API 的**引擎状态）
 *   LC-03b **判别腿**：写一个与 Paris **同时区**、不同经纬度的地点 ⇒
 *         (a) 回读 lat/lon 变了 ∧ (b) UTCOffset **不变**。
 *         没有这条，(b) 就可能是"随便写什么都变"或"本来就变"，读不出因果。
 *   LC-04 **可验算的物理量（绝对腿）**：天文学恒等式「**北天极高度 = 观测者纬度**」。
 *         仪器 = 把**当日天极** `(0,0,1)` 经 `StelCore::equinoxEquToAltAz()` 转进地平坐标，
 *         取高度角。三个地点各测一次，断言 |天极高度角 − 该地点纬度| < 0.5°。
 *         ⚠️ 仪器为什么不用 Polaris（读血泪：这里踩过一整轮冤枉路）：
 *         Polaris 赤纬 +89.26°，偏离天极 0.74° ⇒ 它与任一固定方向的夹角**随时角抖动**，
 *         峰峰值 ~1.5°；而"巴黎(48.85) vs 阿布维尔(50.11)"只差 1.26° ⇒ **分辨不出**。
 *         当日天极严格落在自转轴上 ⇒ `Rz(−θ)` 作用在 z 轴上为恒等 ⇒ **与恒星时无关**，
 *         也没有 J2000↔当日 的岁差偏置 ⇒ 读数**精确等于纬度**，容差能收到 0.5°，
 *         而三地点之间的判别间隙 8.95° ⇒ 判别力 ≈ 18 倍。
 *         这条为什么能证明"写入落到了坐标变换栈"（而不只是落了结构体）：
 *         `matEquinoxEquToAltAz` 每帧由 `position->getRotAltAzToEquatorial()`（吃
 *         `currentLocation` 的经纬度）重建。矩阵陈旧/未重算 ⇒ 读数停在**上一个地点**
 *         的纬度上 ⇒ 必红。
 *   LC-04b **判别腿**：同一仪器在**三个地点**的读数差 ≈ 纬度差（两对：Paris↔Beijing
 *         8.95°、Paris↔Abbeville 1.25°，各 |Δ| < 0.5°）。不依赖任何绝对参考。
 *   LC-05 非法值**无副作用**：lat=91 / lon=200 / alt=1e6 各自被拒 ∧ token 正确
 *         ∧ 当前地点的 **ID 纹丝不动**。
 *   LC-06 not-found：不存在的 ID 被拒 ∧ 同样无副作用。
 *   LC-07 往返：写回**起始地点** ⇒ 经纬度回到起始值（容差 1e-3）。
 *   LC-08 计数：写入次数 / 拒绝次数与预期一致。
 *
 * ── 已知陷阱（照抄时别踩）──────────────────────────────────────────────────
 *   · **时区联动只在跨时区时才可判**：起始地点（引擎默认配的是绵阳）与 Beijing
 *     同属 Asia/Shanghai ⇒ 拿它俩比时区是**假绿**。LC-03a 因此必须选 Paris。
 *   · ⚠️ **别把时钟挪到 1847-12-01 之前**测地点×时区联动：引擎 `getUTCOffset`
 *     在那之前不看时区名、按经度算 LMST（StelCore.cpp:1655）⇒ 假红。
 *   · 🔴 **时区联动还有第二个前提：引擎必须**未启用"自定义时区"****（T33-D 实测）。
 *     `StelCore.cpp:240-243`：config 的 `localization/time_zone` **非空** ⇒ 启动时
 *     `setUseCustomTimeZone(true)`；而 `setObserver` 里的联动
 *     （`StelCore.cpp:1543-1547`）条件含 `!getUseCustomTimeZone()` ⇒ **按设计跳过**。
 *     **实测后果（Windows 那台，config.ini 有 `time_zone = Asia/Shanghai`）**：
 *     正题**恒为 `9/10`**、红项恒为 `LC-03a`、读数 `ΔUTCOffset = 0.00 h`；
 *     而 **LC-03b（"时区**不变**"）假绿** —— 它不是测出来的，是前提失效送的。
 *     连带污染 A（`7/10`，多一条 LC-03a）、B（`9/10`）、C（`7/10`）；**D 不受影响**
 *     （D 不依赖时区腿，两边红项完全一致 ⇒ 反证根因单一）。
 *     ⇒ 处置：**判据自己建立前提**（跑前读 `useCustomTimeZone()`，为 true 就临时置
 *     false 并在末尾**恢复**，见步骤 1 / 步骤 11），**不能靠"这台机器的配置刚好合适"**
 *     （TRAPS 第 12 条）。`setUseCustomTimeZone` **不落盘**（无 `immediateSave`）⇒ 还原即净。
 *     跑批脚本另有一条**前提自证**：日志里必须出现 `flagUseCTZ`，否则说明跑的是旧仪器。
 *   · 🔴 **步骤表里的 `delayAfter` 是"跑完**本步**之后的等待"，不是"等多久再跑本步"**
 *     （`run()` 里的 `tick()`：先 `body(ctx)` 再 `singleShot(delayAfter)`）。
 *     把**写入步**的 `delayAfter` 写成 0 ⇒ 回读步与写入步之间**只隔一个事件循环**
 *     ⇒ 谁先醒是**竞态**：帧泵 tick 先到就读到新地点、回读步先到就读到**上一个地点**
 *     的变换矩阵。**实测后果**：同一二进制，跑一次 9/10、跑一次 8/10，而红的那条
 *     每次都恰好差一个"上一步写的纬度"（10.2°）—— 一度被误诊成"矩阵滞后/产品缺陷"。
 *     处置：**不要依赖"延迟放在哪一步"**，凡是要读**变换栈**的读取步，
 *     一律先过**有界就绪门** `awaitFresh()`（主动跑事件循环让帧泵 tick，
 *     就绪即测、超时**明确判红**，见血泪第 10 条 DYN 先例）。
 *   · 变换栈（`updateTransformMatrices`）由**渲染循环**每帧刷新，"写完地点"本身
 *     不触发重算 ⇒ 任何读几何量的判据都必须等帧（上面那条门的由来）。
 *   · 仪器**不要用 Polaris 当"天极"**（0.74° 偏移 + 时角抖动，见 LC-04 说明）。
 *
 * ── 负控开关（与 `..._FORCE_FOCUSGATE_FAIL` 同款先例，**只用于证明判据承重**）──────
 *   `STELQUICK_LOC_NODELAY=1`  ⇒ 写入步**不给** delayAfter（=0）⇒ 回读步与写入步只隔
 *                                 一个事件循环 ⇒ 竞态复现。
 *   `STELQUICK_LOC_GATE_OFF=1` ⇒ 关掉就绪门（`awaitFresh` 恒真）。
 *   两开关**一起**开 = 复现本轮修掉的间歇红（LC-04 家族读到上一个地点的矩阵）。
 *   ⚠️ **它是概率性的**：被复现的缺陷本身就是**竞态** ⇒ 帧泵**有时**抢先 tick ⇒ 该跑**全绿**。
 *   三批实测（**逐位相同**的二进制）：`5/5` 红、`5/5` 红、**`3/5` 红**。
 *   ⇒ 别把"每次都红"写成判据；只断言"**红项只许是** LC-04/LC-04b"，且整批**至少复现一次**。
 *   只开 `NODELAY` = 由就绪门兜住，应仍全绿。
 *   ⚠️ **不要把"门报出非零探测次数"写成判据**（初版这么写过，已被实测推翻）：
 *   摘掉写入延迟后，帧泵可能**恰好在回读步之前**先跑一拍 ⇒ 门读到的已是新值
 *   ⇒ **探测 0 次也是正确读数**（实测该跑照样 `10/10`）。探测次数只作**信息**。
 *   **"门是承重件"的证据是 A↔B 这一对**：A（门关）**红** ∧ B（门开）**绿**。
 *   ⚠️ 不要写成"A（门关）`8/10`"—— A 的红**是概率性的**（见上），写死条数会在运气好的一跑上报假红。
 *
 * ── 退出码 ─────────────────────────────────────────────────────────────────
 *   0=PASS，10=FAIL，6=UNAVAILABLE（库里取不到 Paris/Beijing 这类必需地点）。
 */
#pragma once

#include <QString>
#include <QStringList>
#include <functional>

class QCoreApplication;

namespace stelapp {

class AppFacade;

class LocationCheck
{
public:
    struct Result
    {
        bool ran = false;
        bool pass = false;
        bool unavailable = false;
        int passed = 0;
        int total = 0;
        QString summary;
        QStringList details;
    };

    //! 全部在 GUI 线程。@p delayMs 后开跑（等引擎数据落定）。结果经 onDone 回传。
    static void run(QCoreApplication *app,
                    AppFacade *facade,
                    const std::function<void(const Result &)> &onDone,
                    int delayMs = 2500);
};

} // namespace stelapp
