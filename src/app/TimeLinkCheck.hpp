/*
 * TimeLinkCheck — T35-C 仿真时间链路自检（STELQUICK_TIMELINK_CHECK=1）。
 *
 * ── 这套判据要定的"性"：T27 的"脱钩"结论是对还是错 ────────────────────────────
 * T27 留档原文（`docs/T27_MOUSE_NAV_UI_CHECK.zh_CN.md` §4 与证据 README）：
 *
 *   > 帧泵推进量（1.5 天/秒）与 `getTimeRate()`（=10）**不一致**；simJD 差 0.61 天
 *   > vs rate=10 该走的 4.6e-5 天，**差 4 个数量级**。若这是设计（帧推进走固定
 *   > 步长，rate 只管别的语义）则需文档说明，否则是独立的时间链路缺陷。
 *
 * 复查代码后，那句结论的**结论链有三处可独立致错的环节**：
 *
 *  ① **单位误读**：`StelCore.hpp:595` 原文 "Get time speed in JDay/sec"，
 *     `advanceHostDriven` 也把 `timeSpeed` **直接当"天/秒"**用
 *     （`StelClockController.cpp:28`：`m_jd += dtWall × ratePerSecond × scale`）。
 *     而 T27 的算术 `10 × JD_SECOND × 0.4 = 4.6e-5` 是按"× 实时倍率"算的
 *     —— 把 JDay/sec 当倍率用，**凭空引入 1/86400 的因子**。
 *  ② **rate 读数在套件内是移动靶**：INTERACTCHECK 的 **IT-05 自己就注入 L 键**
 *     ⇒ `increaseTimeSpeed()`（阶梯 ×10：`StelCore.cpp:2298-2306`）⇒ 同一进程里
 *     rate 会被测试自己从 0.1 改到 1、再到 10。证据里 DIAG9 的 `engineRate` 在
 *     0.1 / 1 / 10 之间跳（`docs/evidence/2026-09-29-w-t29/*`）就是它。
 *  ③ **窗口长度从未测量**："400ms" 是**相位名义 delay**，从没有与 ΔJD
 *     **同一时刻**量过真实墙钟。而 ΔJD 是与**真实墙钟**线性相关的物理量。
 *
 * ⇒ 所以本套判据的核心动作是：**在同一时刻把三个量（ΔJD / 自测墙钟 W /
 *   `core->getTimeRate()`）量齐**，看 `ΔJD == W × rate × scale` 成不成立。
 *   成立 ⇒ 无脱钩，T27 的口径错在①/②/③；不成立 ⇒ 真缺陷，另行立项。
 *
 * ⚠️ **墙钟必须自测**：`W` 走本文件自己的 `QElapsedTimer`（与帧泵内部那只
 *   `LiveSkyRuntime::m_simClock` 不同实例、不同代码路径）⇒ 不是"自洽假绿"。
 *   采样本身在**同一个步骤体**里连续完成（帧泵是 GUI 线程 QTimer，步骤体执行期间
 *   不可能重入 ⇒ 天然是同刻快照，不需要锁）。
 *
 * ── 🔴 窗口就绪门（有界；定稿轮新增，治"假红"）────────────────────────────────
 *   本套判据全都用 `QTimer::singleShot(delayAfter)` 划窗。事件循环一旦被饿住
 *   （批次连跑 11 套件 / Spotlight / 上一个进程的 Metal 拆卸），**定时器与帧泵同源
 *   停摆** ⇒ 窗口被拖长、ΔJD 又少涨 —— 两个量被**同一个**抖动污染 ⇒ 该窗
 *   **没有分辨力**。实测：档A 名义 1.5s 被拖到 **2.19s**，把 TL-02 打红 1/5 跑。
 *   处置沿 T22/T27/T28/T33「有界就绪门」先例：**W 超名义 25% ⇒ 本窗不可判 ⇒
 *   重起窗、把本步原样重跑**（单窗预算 3 次）。判据里的 `if (r.suspect) return;`
 *   就是这条门的短路点。
 *   ⚠️ 门是**单边**的（`singleShot` 只会晚不会早 ⇒ W < 名义不可能），且**真缺陷不改
 *   墙钟**（链路半速不改 W）⇒ **门不会掩护真缺陷**。预算耗尽后仍按现状判定，并在
 *   日志里写明"读数可能受环境污染"（**不洗成 PASS**）。
 *
 * ── 判据清单（TL-01..TL-07；前提不齐 ⇒ 整套 UNAVAILABLE）─────────────────────
 *   TL-01 **链路自洽（主判据）**：窗口 W≈3.0s、rate=0.2 ⇒ ΔJD 与
 *         `W × rate(同刻读) × scale` 的相对偏差 ≤ **15%**；并断言**窗口内 rate
 *         读数不变**（T27 陷阱②的编码：若被测对象==移动靶，本判据直接红）。
 *   TL-02 **rate 多档线性（成对）**：rate 0.2 与 0.8 各一窗口 ⇒ **速率归一化**后之比
 *         `(ΔJD_B/W_B)/(ΔJD_A/W_A)` ≈ 4（±30%）。证明"rate 真的进了链路"。
 *         ⚠️ 断言**只认归一化比值**，不认"两窗长度差"：初版额外断言"长度差 ≤20%"，
 *         定稿轮被**调度抖动**打红（档A 名义 1.5s 被拖到 **2.19s**）⇒ 假红 1/5 跑。
 *         抖动期间事件循环被饿住、帧泵同源停摆 ⇒ ΔJD 也不涨 ⇒ **裸比值**必然偏；
 *         归一化之后这个耦合在解析上就断了。长度差**降为读数**。
 *   TL-03 **窗口线性**：rate=0.4 下 W≈0.8s 与 W≈2.4s ⇒ ΔJD 之比 ≈ 3（±35%）。
 *         **直接反驳** T27 README 自己列出的备选假设"帧泵按固定步长推进、
 *         rate 只管别的语义"——那会让比值趋近 1:1。
 *   TL-04 **冻结 / 恢复不补**：scale=0 窗口 ⇒ |ΔJD| ≤ 1e-9；恢复后一窗口
 *         ΔJD ∈ 预期×[0.4, 1.6]（上界 1.6 就是"有没有把冻结期补回来"的判别；
 *         下界**刻意远离 1** —— 理由见负控 A/B/C 那段）。
 *   TL-05 **速率阶梯台账 + 阶梯后链路跟变**：`setTimeRate(0.1)` →
 *         `increaseTimeSpeed()` ⇒ 读数 1.0；两档同长窗口的 ΔJD 之比 ≈ 10（±40%）。
 *         这条**解释** T27 里 `engineRate` 读数为何是 10（第 2 次 L 键）——即②。
 *   TL-06 **读面同源**：时钟模式 == HostDriven ∧ `getJD()`（上一帧快照）与
 *         `getSimClockJD()`（真源）之差 ≤ max(1e-6, rate×0.2s) ∧
 *         `facade.julianDay()` 与真源之差 ≤ 1e-9（防"第二个时间源"）。
 *   TL-07 **恒星时腿（绝对恒等式 + 下游重算）**：ΔLST 与 `ΔJD × 360.9856°`
 *         残差 ≤ `max(1.0°, 期望×0.1%)`，且**固定的 J2000 方向**经引擎 `j2000ToAltAz`
 *         的落点在同窗口内转过 > 10°（ΔJD≈0.2 天 ⇒ 期望 ≈74°）。
 *         ⚠️ 这是"把时间链路验到画面/坐标系上"的独立路径 —— T30 铁律：
 *         "设了新值"证明不了下游重算过，必须用**可验算的物理量**当判据。
 *         它同时是单位腿：若 sim 时钟快/慢 86400 倍（T27 算术隐含的怀疑），
 *         `ΔJD×360.9856` 与真实 ΔLST 立刻对不上。
 *
 * ── 负控开关（证明判据承重；三组红项**互不相同**，实测见下）──────────────────
 *   A `STELQUICK_TIMELINK_BREAK=1`       帧泵传 `dt×0.5`（推进量与墙钟脱钩）
 *     ⇒ 实测 **只红 TL-01**（6/7）：TL-02/03/05 都是**比值**判据，整体缩放不改变
 *       比值；TL-07 是**恒等式**（ΔJD 与 ΔLST 一起缩放，恒等仍成立）；TL-04 的
 *       恢复腿比值 0.5 —— 它的带宽下界**刻意设在 0.4**（不是 0.5），就是为了让
 *       "链路整体半速"这件事**归 TL-01 管**，不让 TL-04 因边界重合而随机变红
 *       （实测 0.4990 ↔ 0.5002，会漂）。
 *   B `STELQUICK_TIMELINK_RATE_IGNORED=1` 帧泵用**钉死的 0.1** 推进，但
 *     `getTimeRate()` 仍返回用户设的值（**复现 T27 README 假设的那个缺陷形态**：
 *     "rate 只管别的语义，推进走固定量"）
 *     ⇒ 实测红 **TL-01、TL-02、TL-05**（4/7）：TL-01 抓"ΔJD≠W×rate"、TL-02/05 抓
 *       "ΔJD 不随 rate 成比例"；TL-03（同 rate 下两窗口之比）是**比值之比**、
 *       TL-06/07 照绿、TL-04 恢复腿比值 0.5 落带内照绿。
 *   C `STELQUICK_TIMELINK_FREEZE_LEAK=1` 冻结（scale=0）期间**照旧推进**（推进的
 *     一瞬间把 scale 解成 1、推完写回 0 ⇒ **读数**仍是冻结，链路却漏了）
 *     ⇒ 实测 **只红 TL-04**（6/7）：冻结窗 ΔJD = 0.5·W·rate ≠ 0，直接破 TL-04 的
 *       "冻结必须真零"那条腿。
 *   ⇒ A/B/C 的红项集合**两两不同**（{TL-01} / {TL-01,TL-02,TL-05} / {TL-04}），
 *     A 把 TL-01 单独隔离、C 把 TL-04 单独隔离 ⇒ "链路自洽"、"rate 真进链路"、
 *     "冻结必须真零"三条腿**各自承重**。
 *     ⚠️ 已知未覆盖的腿（**如实记录，不假装全覆盖**）：TL-03 的"按帧固定步长"、
 *     TL-04 的"不许补"（上界 1.6）、TL-06 的"第二时间源"。TL-03 与 TL-01 测的是
 *     同一个量（ΔJD ∝ 真实墙钟）的两种取法，A 已覆盖该机理；TL-06 是结构性恒等式，
 *     只能靠注入第二个时间源才可证伪。**曾试过**用"解冻后补回冻结期"当 C 来咬
 *     TL-04 的上界，但它不可靠：解冻后检查要等 300ms 才 `arm()`，"补"的那一脚
 *     落在开窗**之前** ⇒ 判据照绿（比值 0.9947）—— 负控形状对、落点不对。
 *
 * ── 退出码 ─────────────────────────────────────────────────────────────────
 *   0=PASS，10=FAIL，6=UNAVAILABLE（引擎未引导/HostDriven 未接管）。
 */
#pragma once

#include <QString>
#include <QStringList>
#include <functional>

class QCoreApplication;

namespace stelapp {

class AppFacade;

class TimeLinkCheck
{
public:
    struct Result
    {
        bool ran = false;
        bool pass = false;
        bool unavailable = false;
        int passed = 0;
        int total = 0;
        QString summary;
        QStringList details;
    };

    //! 全部在 GUI 线程。@p delayMs 后开跑（等引擎引导、帧泵稳态）。结果经 onDone 回传。
    static void run(QCoreApplication *app,
                    AppFacade *facade,
                    const std::function<void(const Result &)>& onDone,
                    int delayMs = 2500);
};

} // namespace stelapp
